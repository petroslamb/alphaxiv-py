def _normalize(value: str) -> str:
    return re.sub(r"[\W_]+", " ", value.casefold()).strip()


def search_topics(query: str) -> list[str]:
    """Return matching topic slugs, ranked by exact match then prefix.

    Lookup is local and lexical, as in the current website's topic selector;
    it no longer performs the retired endpoint's semantic nearest-topic search.
    """
    normalized = _normalize(query)
    if not normalized:
        return []
    matches: dict[str, int] = {}
    for code, slug in TOPICS:
        aliases = (_normalize(code), _normalize(slug))
        if any(normalized in alias for alias in aliases):
            rank = min(
                0 if alias == normalized else 1 if alias.startswith(normalized) else 2
                for alias in aliases
            )
            matches[slug] = min(matches.get(slug, rank), rank)
    return sorted(matches, key=lambda slug: (matches[slug], slug))
